/**
 * Engine-v2 conformance: replays packages/core/fixtures/engine/conformance.json (generated by the TypeScript engine)
 * and requires identical outcomes — status, error, virtual duration, counters, retry delays, timeouts, log lines,
 * click/drag coordinates and typed text. Multi-monitor cases also script displays and probe answers and compare the
 * final variables and every probe; dhash.json checks the scene hash bit for bit.
 */
class ConformanceTest {
    private val file: File by lazy {
        System.getProperty("autoflow.fixtures")?.let { File(it, "engine/conformance.json") }?.takeIf { it.isFile }
            ?: javaClass.classLoader.getResource("fixtures/engine/conformance.json")?.let { File(it.toURI()) }
            ?: error("packages/core/fixtures/engine/conformance.json not found — run `pnpm --filter @autoflow/core build` first")
    }

    /** JSON numbers compared by value, so 100 and 100.0 are equal. */
    private fun norm(e: JsonElement): JsonElement = when (e) {
        is JsonArray -> JsonArray(e.map { norm(it) })
        is JsonObject -> JsonObject(e.mapValues { norm(it.value) })
        is JsonPrimitive -> if (!e.isString && e.doubleOrNull != null) JsonPrimitive(e.doubleOrNull!!) else e
        else -> e
    }

    private fun point(t: Target): JsonElement = when (t) {
        is Target.Point -> buildJsonArray { add(JsonPrimitive(t.x)); add(JsonPrimitive(t.y)) }
        is Target.Region -> buildJsonArray { add(JsonPrimitive(t.x)); add(JsonPrimitive(t.y)); add(JsonPrimitive(t.w)); add(JsonPrimitive(t.h)) }
        else -> error("unexpected target $t")
    }

    private fun script(e: JsonElement?): Map<String, List<String>> =
        (e as? JsonObject)?.mapValues { (_, v) -> v.jsonArray.map { it.jsonPrimitive.content } } ?: emptyMap()

    private fun displays(e: JsonElement?): List<DisplayInfo>? = (e as? JsonArray)?.map { d ->
        val o = d.jsonObject
        fun rect(k: String) = o[k]!!.jsonObject.let { r -> Target.Rect(r["x"]!!.jsonPrimitive.doubleOrNull!!, r["y"]!!.jsonPrimitive.doubleOrNull!!, r["w"]!!.jsonPrimitive.doubleOrNull!!, r["h"]!!.jsonPrimitive.doubleOrNull!!) }
        DisplayInfo(
            o["id"]!!.jsonPrimitive.content, o["name"]!!.jsonPrimitive.content, o["primary"]!!.jsonPrimitive.content == "true",
            rect("bounds"), rect("workArea"), o["scale"]!!.jsonPrimitive.doubleOrNull!!, o["orientation"]!!.jsonPrimitive.content,
        )
    }

    @Test fun engineV2MatchesTheTypeScriptEngine() {
        val cases = Json.parseToJsonElement(file.readText()).jsonArray
        assertTrue("expected conformance cases", cases.size >= 10)
        for (c in cases.map { it.jsonObject }) {
            val name = c["name"]!!.jsonPrimitive.content
            val flow = try {
                FlowParser.parse(c["flow"]!!)
            } catch (e: FlowParseException) {
                fail("$name: ${e.message}")
                return
            }
            val backend = FakeBackend(
                platform = Platform.WINDOWS,
                displayList = displays(c["displays"]),
                pixels = script(c["pixels"]),
                sceneHashes = script(c["sceneHashes"]),
            )
            (c["failFirst"] as? JsonObject)?.let { ff ->
                val type = ff["type"]!!.jsonPrimitive.content
                var left = ff["count"]!!.jsonPrimitive.longOrNull!!
                backend.failNext = { a -> if (a.type == type && left > 0) { left--; BackendException("target not found", ErrorCategory.TARGET) } else null }
            }
            val random = c["random"]!!.jsonPrimitive.doubleOrNull!!
            val secrets = (c["secrets"] as? JsonObject)?.mapValues { it.value.jsonPrimitive.content } ?: emptyMap()
            val events = ArrayList<RunEvent>()
            val r = runBlocking {
                FlowRun(
                    flow,
                    backend,
                    RunOptions(
                        clock = VirtualClock(1_000_000),
                        skipCountdown = true,
                        random = { random },
                        confirmRisk = { true },
                        secret = { secrets[it] },
                        onEvent = { events.add(it) },
                    ),
                ).start()
            }
            val e = c["expect"]!!.jsonObject
            assertEquals("$name: status", e["status"]!!.jsonPrimitive.content, r.status.json)
            val gotError: JsonElement = r.error?.let { err ->
                buildJsonObject {
                    put("category", err.category.json)
                    if (err.stepId != null) put("stepId", err.stepId) else put("stepId", JsonNull)
                    put("message", err.message)
                }
            } ?: JsonNull
            assertEquals("$name: error", e["error"], gotError)
            assertEquals("$name: durationMs", e["durationMs"]!!.jsonPrimitive.longOrNull, r.durationMs)
            assertEquals("$name: actions", e["actions"]!!.jsonPrimitive.longOrNull, r.actions)
            assertEquals("$name: iterations", e["iterations"]!!.jsonPrimitive.longOrNull, r.iterations)
            assertEquals("$name: steps", e["steps"]!!.jsonPrimitive.longOrNull, r.steps)
            assertEquals("$name: retry delays", e["retryDelays"]!!.jsonArray.map { it.jsonPrimitive.longOrNull }, events.filterIsInstance<RunEvent.Retry>().map { it.delayMs })
            assertEquals("$name: timeouts", e["timeouts"]!!.jsonArray.map { it.jsonPrimitive.content }, events.filterIsInstance<RunEvent.Timeout>().map { it.stepId })
            assertEquals("$name: logs", e["logs"]!!.jsonArray.map { it.jsonPrimitive.content }, events.filterIsInstance<RunEvent.Log>().map { it.message })
            val targets = JsonArray(
                backend.effects.flatMap { fx ->
                    when (val a = fx.action) {
                        is InputAction.Click -> listOf(point(a.target))
                        is InputAction.Drag -> listOf(point(a.from), point(a.to))
                        else -> emptyList()
                    }
                },
            )
            assertEquals("$name: targets", norm(e["targets"]!!), norm(targets))
            assertEquals("$name: typed", e["typed"]!!.jsonArray.map { it.jsonPrimitive.content }, backend.typed)
            e["probes"]?.let { want ->
                val got = JsonArray(backend.probes.map { p -> JsonArray(p.map { JsonPrimitive(it) }) })
                assertEquals("$name: probes", norm(want), norm(got))
            }
            e["vars"]?.let { want ->
                assertEquals("$name: vars", norm(want), norm(JsonObject(r.vars.mapValues { it.value.toJson() })))
            }
        }
    }

    @Test fun dhashMatchesTheTypeScriptEngineBitForBit() {
        val fx = Json.parseToJsonElement(File(file.parentFile, "dhash.json").readText()).jsonObject
        val images = fx["images"]!!.jsonArray
        assertTrue(images.size >= 8)
        val hashes = HashMap<String, String>()
        for (im in images.map { it.jsonObject }) {
            val name = im["name"]!!.jsonPrimitive.content
            val hex = im["rgb"]!!.jsonPrimitive.content
            val bytes = ByteArray(hex.length / 2) { hex.substring(it * 2, it * 2 + 2).toInt(16).toByte() }
            val got = dhashBytes(bytes, im["w"]!!.jsonPrimitive.longOrNull!!.toInt(), im["h"]!!.jsonPrimitive.longOrNull!!.toInt(), 3)
            assertEquals(name, im["hash"]!!.jsonPrimitive.content, got)
            hashes[name] = got!!
        }
        for (p in fx["pairs"]!!.jsonArray.map { it.jsonObject }) {
            val sim = hashSimilarity(hashes[p["a"]!!.jsonPrimitive.content]!!, hashes[p["b"]!!.jsonPrimitive.content]!!)
            assertEquals(p.toString(), p["similarity"]!!.jsonPrimitive.doubleOrNull!!, sim, 0.0)
        }
    }

    @Test fun stageRunPausesOnTakeoverAndScreenProbesAreBlockedOnAndroid() {
        val base = """"schemaVersion":"1.0","id":"f","name":"t","createdAt":"2026-10-19T00:00:00.000Z","updatedAt":"2026-10-19T00:00:00.000Z""""
        val flow = FlowParser.parse(
            """{$base,"stage":{"display":"secondary"},"steps":[
                {"id":"a","type":"click","target":{"kind":"point","x":0.5,"y":0.5,"space":"normalized"}},
                {"id":"n","type":"notify","title":"x"},
                {"id":"b","type":"click","target":{"kind":"point","x":0.6,"y":0.5,"space":"normalized"}}]}""",
        )
        val desk = listOf(DisplayInfo("MAIN", "MAIN", true, Target.Rect(0.0, 0.0, 1920.0, 1080.0)), DisplayInfo("SIDE", "SIDE", false, Target.Rect(1920.0, 0.0, 1280.0, 1024.0)))
        val backend = FakeBackend(platform = Platform.WINDOWS, displayList = desk)
        backend.failNext = { a -> if (a is InputAction.Notify) backend.pointer = 100 to 100; null }
        val logs = ArrayList<String>()
        val run = FlowRun(flow, backend, RunOptions(clock = VirtualClock(0), skipCountdown = true, onEvent = { if (it is RunEvent.Log) logs.add(it.message) }))
        val result = runBlocking {
            val job = async { run.start() }
            while (run.currentState != RunState.PAUSED) delay(1)
            assertEquals(1, backend.effects.count { it.action is InputAction.Click })
            run.resume()
            job.await()
        }
        assertEquals(RunStatus.COMPLETED, result.status)
        assertEquals(listOf("takeover: pointer left the stage display, run paused"), logs)
        assertEquals(2, backend.effects.count { it.action is InputAction.Click })

        val probe = FlowParser.parse("""{$base,"steps":[{"id":"p","type":"pixelCheck","at":{"kind":"point","x":1,"y":1},"resultVar":"c"}]}""")
        val r = runBlocking { FlowRun(probe, FakeBackend(), RunOptions(clock = VirtualClock(0), skipCountdown = true)).start() }
        assertEquals(ErrorCategory.UNSUPPORTED, r.error?.category)
        assertTrue(isRunnableOn(probe.steps, Platform.WINDOWS))
    }

    @Test fun wallClockTimeoutPreemptsAHangingAction() {
        val flow = FlowParser.parse(
            """{"schemaVersion":"1.0","id":"f","name":"t","createdAt":"2026-10-19T00:00:00.000Z","updatedAt":"2026-10-19T00:00:00.000Z",
               "steps":[{"id":"c","type":"click","target":{"kind":"point","x":1,"y":1},"stepTimeoutMs":50}]}""",
        )
        val t0 = System.currentTimeMillis()
        val r = runBlocking { FlowRun(flow, FakeBackend(actionDelayMs = 10_000), RunOptions(clock = RealClock, skipCountdown = true)).start() }
        assertEquals(RunStatus.FAILED, r.status)
        assertEquals(ErrorCategory.TIMEOUT, r.error?.category)
        assertEquals("c", r.error?.stepId)
        assertTrue("took ${System.currentTimeMillis() - t0} ms", System.currentTimeMillis() - t0 < 3000)
    }

    @Test fun mulberry32MatchesTheReferenceValues() {
        val r = Mulberry32(42)
        assertEquals(listOf(601_103_752L, 448_290_559L, 852_465_793L), (0 until 3).map { Math.round(r.next() * 1e9) })
    }

    @Test fun retryDelayCurves() {
        assertEquals(listOf(500L, 1000L, 1500L), (1..3).map { retryDelayMs(OnError("retry", 3, 500), it) { 0.0 } })
        val exp = OnError("retry", 5, 100, backoff = "exponential", maxBackoffMs = 1000)
        assertEquals(listOf(100L, 200L, 400L, 800L, 1000L), (1..5).map { retryDelayMs(exp, it) { 0.0 } })
        assertEquals(300L, retryDelayMs(OnError("retry", 1, 400, backoff = "fixed", jitter = 0.5), 1) { 0.5 })
    }

    @Test fun hostileDocumentsFailWithIssues() {
        val base = """"schemaVersion":"1.0","id":"f","name":"t","createdAt":"2026-10-19T00:00:00.000Z","updatedAt":"2026-10-19T00:00:00.000Z""""
        var deep = """{"id":"w","type":"wait","ms":1}"""
        repeat(5000) { deep = """{"id":"g$it","type":"group","name":"g","body":[$deep]}""" }
        val e1 = runCatching { FlowParser.parse("{$base,\"steps\":[$deep]}") }.exceptionOrNull()
        assertTrue("deep nesting must be rejected, got $e1", e1 is FlowParseException || e1 is kotlinx.serialization.SerializationException)
        var nested = """{"id":"w","type":"wait","ms":1}"""
        repeat(40) { nested = """{"id":"g$it","type":"group","name":"g","body":[$nested]}""" }
        val e2 = runCatching { FlowParser.parse("{$base,\"steps\":[$nested]}") }.exceptionOrNull() as? FlowParseException
        assertTrue("${e2?.message}", e2?.issues?.any { "nested" in it.message } == true)
        val far = runCatching { FlowParser.parse("""{$base,"steps":[{"id":"c","type":"click","target":{"kind":"point","x":1e300,"y":0}}]}""") }
        assertTrue(far.isFailure)
        val header = runCatching { FlowParser.parse("""{$base,"steps":[{"id":"h","type":"http","url":"https://x.dev","headers":{"bad header":"v"}}]}""") }
        assertTrue(header.isFailure)
        val ok = FlowParser.parse("""{$base,"steps":[{"id":"w","type":"wait","ms":10,"stepTimeoutMs":5,"onError":{"strategy":"retry","backoff":"exponential","jitter":0.3}}],"limits":{"maxSteps":9},"humanize":{"offsetPx":3,"seed":7}}""")
        assertEquals(5L, ok.steps[0].meta.stepTimeoutMs)
        assertEquals(9L, ok.limits.maxSteps)
        assertEquals(Humanize(3, 0, 7), ok.humanize)
    }

    @Test fun expressionWorkIsBounded() {
        val env = ExprEnv(mutableMapOf("s" to Value.Str("a".repeat(2000))))
        val t0 = System.currentTimeMillis()
        val err = runCatching { evalExpr("replace(s, \"\", s)", env) }.exceptionOrNull()
        assertTrue("$err", err is ExprError && "too large" in (err.message ?: ""))
        assertEquals(Value.Str("a-b-c"), evalExpr("replace(\"abc\", \"\", \"-\")", env))
        val hostile = "{{" + " ".repeat(20_000) + "{".repeat(20_000)
        assertEquals(hostile, interpolate(hostile, env))
        assertEquals("x 3 y", interpolate("x {{ 1 + 2 }} y", env))
        assertEquals("k=${SECRET_MASK}", interpolate("k={{secret:a}}", env, maskSecrets = true) { "v" })
        assertTrue(System.currentTimeMillis() - t0 < 5000)
    }
}
